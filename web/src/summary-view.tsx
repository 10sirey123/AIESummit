import { useMemo, useState } from 'react';
import { CalendarPlus, Copy, FileDown, FileText } from 'lucide-react';
import type { PageResult } from './api';
import { detectDates, icsFile, relative, type DetectedDate } from './contract-dates';
import { evaluate, type Evaluation, type Rule, type Tier } from './playbook-store';
import { TierBadge, type Decision, type ReviewFinding } from './review-desk';

type Ask = { finding: ReviewFinding; evaluation: Evaluation; decision?: Decision };
const askTiers: Tier[] = ['Walk-away', 'Escalate', 'Fallback'];
const dateFormat = new Intl.DateTimeFormat(undefined, { dateStyle: 'medium', timeZone: 'UTC' });

function download(name: string, type: string, text: string) {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const link = document.createElement('a');
  link.href = url; link.download = name; link.click();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}
const baseName = (fileName: string) => fileName.replace(/\.[a-z0-9]+$/i, '');
const escapeHtml = (text: string) => text.replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]!));

/** Asks: every Walk-away / Escalate / Fallback finding the reviewer has not rejected, most serious first. */
export function negotiationAsks(findings: ReviewFinding[], rules: Rule[], decisions: Record<string, Decision>): Ask[] {
  return findings.map(finding => ({ finding, evaluation: evaluate(finding, rules), decision: decisions[finding.key] }))
    .filter(ask => askTiers.includes(ask.evaluation.tier) && ask.decision?.decision !== 'rejected')
    .sort((a, b) => askTiers.indexOf(a.evaluation.tier) - askTiers.indexOf(b.evaluation.tier) || a.finding.page - b.finding.page);
}

export function memoMarkdown(fileName: string, playbook: string, asks: Ask[], reviewed: number, total: number) {
  const lines = [`# Negotiation summary: ${fileName}`, '', `Playbook: ${playbook} · ${reviewed} of ${total} findings reviewed · ${asks.length} asks`, ''];
  for (const tier of askTiers) {
    const group = asks.filter(ask => ask.evaluation.tier === tier);
    if (!group.length) continue;
    lines.push(`## ${tier}`, '');
    group.forEach((ask, index) => {
      const rule = ask.evaluation.rule;
      lines.push(`${index + 1}. **${ask.finding.heading}** (p.${ask.finding.page}, ${ask.finding.type}${ask.decision ? ', accepted' : ', not yet reviewed'})`);
      lines.push(`   - Contract says: “${ask.finding.quote}”`);
      if (rule?.preferred) lines.push(`   - Our position: ${rule.preferred}`);
      if (rule?.fallback) lines.push(`   - Proposed wording: ${rule.fallback}`);
      if (rule) lines.push(`   - Sign-off: ${rule.signOff}`);
    });
    lines.push('');
  }
  lines.push('_Generated by ClauseLens from AI-detected findings and your playbook. Not legal advice; verify against the source document._');
  return lines.join('\n');
}

function memoEmail(fileName: string, asks: Ask[]) {
  const body = asks.map((ask, index) => `${index + 1}. ${ask.finding.heading} (section on page ${ask.finding.page})\n   ${ask.evaluation.rule?.fallback ? `We propose: ${ask.evaluation.rule.fallback}` : ask.evaluation.rule?.preferred ? `Our position: ${ask.evaluation.rule.preferred}` : 'We would like to discuss this clause.'}`).join('\n\n');
  return `Subject: Proposed changes to ${baseName(fileName)}\n\nHi,\n\nThank you for sending the agreement. Before signing, we would like to propose the following changes:\n\n${body}\n\nHappy to discuss.\n\nBest regards,`;
}

function memoWordHtml(fileName: string, playbook: string, asks: Ask[]) {
  const rows = asks.map(ask => `<tr><td>${escapeHtml(ask.evaluation.tier)}</td><td><b>${escapeHtml(ask.finding.heading)}</b><br/>p.${ask.finding.page} · ${escapeHtml(ask.finding.type)}</td><td>“${escapeHtml(ask.finding.quote)}”</td><td>${escapeHtml(ask.evaluation.rule?.preferred ?? '')}</td><td>${escapeHtml(ask.evaluation.rule?.fallback ?? '')}</td></tr>`).join('');
  return `<html><head><meta charset="utf-8"><title>Negotiation summary</title><style>body{font-family:Arial,sans-serif;font-size:11pt}table{border-collapse:collapse;width:100%}td,th{border:1px solid #999;padding:6px;vertical-align:top}th{background:#eee}</style></head><body><h1>Negotiation summary: ${escapeHtml(fileName)}</h1><p>Playbook: ${escapeHtml(playbook)} · ${asks.length} asks</p><table><tr><th>Tier</th><th>Clause</th><th>Contract says</th><th>Our position</th><th>Proposed wording</th></tr>${rows}</table><p><i>Generated by ClauseLens from AI-detected findings and your playbook. Not legal advice.</i></p></body></html>`;
}

export function NegotiationSummary({ fileName, playbook, findings, rules, decisions, onOpen, onReviewSections }: {
  fileName: string; playbook: string; findings: ReviewFinding[]; rules: Rule[]; decisions: Record<string, Decision>; onOpen: (finding: ReviewFinding) => void;
  onReviewSections?: () => void;
}) {
  const asks = negotiationAsks(findings, rules, decisions);
  const [excluded, setExcluded] = useState<Set<string>>(new Set());
  const [copied, setCopied] = useState(false);
  const chosen = asks.filter(ask => !excluded.has(ask.finding.key));
  const reviewed = findings.filter(item => decisions[item.key]).length;
  const toggle = (key: string) => setExcluded(current => { const next = new Set(current); if (next.has(key)) next.delete(key); else next.add(key); return next; });

  return <section className="summary-view" aria-labelledby="summary-title">
    <div className="summary-head">
      <div>
        <h3 id="summary-title">Negotiation summary</h3>
        <p className="detail-muted">{asks.length} {asks.length === 1 ? 'ask' : 'asks'} from {playbook} · {reviewed} of {findings.length} page sections reviewed{asks.some(ask => !ask.decision) ? ' · unreviewed asks are marked' : ''}. Rejected findings are left out.</p>
        <p className="summary-scope">Based on page sections and your playbook. Extracted-term confirmations and flags are separate.</p>
        {onReviewSections && <button className="text-button" onClick={onReviewSections}>Review page sections</button>}
      </div>
      <div className="summary-actions">
        <button type="button" className="button primary small" disabled={!chosen.length} onClick={() => { void navigator.clipboard?.writeText(memoEmail(fileName, chosen)).then(() => setCopied(true)).catch(() => setCopied(false)); }}><Copy size={14} aria-hidden="true" /> {copied ? 'Copied' : 'Copy as email'}</button>
        <button type="button" className="button secondary small" disabled={!chosen.length} onClick={() => download(`${baseName(fileName)}-negotiation.md`, 'text/markdown;charset=utf-8', memoMarkdown(fileName, playbook, chosen, reviewed, findings.length))}><FileText size={14} aria-hidden="true" /> Memo (.md)</button>
        <button type="button" className="button secondary small" disabled={!chosen.length} onClick={() => download(`${baseName(fileName)}-negotiation.doc`, 'application/msword', memoWordHtml(fileName, playbook, chosen))}><FileDown size={14} aria-hidden="true" /> Word (.doc)</button>
      </div>
    </div>
    {!asks.length ? <p className="summary-empty">Nothing to negotiate: no finding is tiered Walk-away, Escalate or Fallback by the active playbook (or those findings were rejected).</p>
      : <ol className="ask-list">
        {asks.map(ask => {
          const rule = ask.evaluation.rule;
          const included = !excluded.has(ask.finding.key);
          return <li key={ask.finding.key} data-included={included || undefined}>
            <label className="ask-check"><input type="checkbox" checked={included} onChange={() => toggle(ask.finding.key)} /><span className="visually-hidden">Include {ask.finding.heading}</span></label>
            <div className="ask-body">
              <div className="ask-top">
                <TierBadge tier={ask.evaluation.tier} />
                <strong>{ask.finding.heading}</strong>
                <button type="button" className="text-button" onClick={() => onOpen(ask.finding)}>p.{ask.finding.page} · show in document</button>
                {!ask.decision && <span className="ask-unreviewed">not yet reviewed</span>}
              </div>
              <p className="ask-quote">“{ask.finding.quote.length > 220 ? `${ask.finding.quote.slice(0, 220)}…` : ask.finding.quote}”</p>
              {rule?.preferred && <p className="ask-line"><span>Our position</span>{rule.preferred}</p>}
              {rule?.fallback && <p className="ask-line"><span>Proposed wording</span>{rule.fallback}</p>}
            </div>
          </li>;
        })}
      </ol>}
    {asks.length > 0 && <p className="detail-muted">{chosen.length} of {asks.length} {asks.length === 1 ? 'ask' : 'asks'} selected for export.</p>}
  </section>;
}

export function KeyDates({ fileName, pages, onOpen }: { fileName: string; pages: PageResult[]; onOpen: (page: number, sentence: string) => void }) {
  const { dates, periods } = useMemo(() => detectDates(pages), [pages]);
  const now = Date.now();
  const future = dates.filter(item => item.date.getTime() >= now - 86_400_000);
  const span = dates.length ? { from: Math.min(dates[0].date.getTime(), now), to: Math.max(dates.at(-1)!.date.getTime(), now) } : undefined;
  const position = (time: number) => span && span.to > span.from ? `${((time - span.from) / (span.to - span.from)) * 100}%` : '50%';
  const next = future[0];

  return <section className="dates-view" aria-labelledby="dates-title">
    <div className="summary-head">
      <div>
        <h3 id="dates-title">Key dates</h3>
        <p className="detail-muted">Detected directly from page text, separately from extracted terms. Calculated dates show their formula; check them against the source.</p>
      </div>
      <div className="summary-actions">
        <button type="button" className="button primary small" disabled={!future.length} onClick={() => download(`${baseName(fileName)}-dates.ics`, 'text/calendar;charset=utf-8', icsFile(baseName(fileName), future))}>
          <CalendarPlus size={14} aria-hidden="true" /> Add {future.length || ''} upcoming to calendar</button>
      </div>
    </div>

    {next && <div className="next-date">
      <span className="next-date-count">{relative(next.date, now)}</span>
      <span><strong>{next.kind}</strong> · {dateFormat.format(next.date)}{next.calculated ? ` · calculated (${next.calculated})` : ''}</span>
    </div>}

    {span && dates.length > 0 && <div className="timeline" aria-label="Timeline of detected dates">
      <div className="timeline-axis" />
      <span className="timeline-today" style={{ left: position(now) }}><span>today</span></span>
      {dates.map((item, index) => <button key={item.key} type="button" className="timeline-dot" data-kind={item.kind} data-past={item.date.getTime() < now || undefined}
        style={{ left: position(item.date.getTime()), top: index % 2 ? '58%' : '18%' }} title={`${item.kind} · ${dateFormat.format(item.date)}`} onClick={() => onOpen(item.page, item.sentence)}>
        <span className="timeline-label">{item.kind}<br />{dateFormat.format(item.date)}</span>
      </button>)}
      <div className="timeline-scale"><span>{dateFormat.format(new Date(span.from))}</span><span>{dateFormat.format(new Date(span.to))}</span></div>
    </div>}

    {!dates.length && !periods.length && <p className="summary-empty">No dates or time periods were detected in this contract’s text.</p>}
    {dates.length > 0 && <table className="dates-table">
      <thead><tr><th scope="col">Date</th><th scope="col">What</th><th scope="col">When</th><th scope="col">Source</th></tr></thead>
      <tbody>{dates.map((item: DetectedDate) => <tr key={item.key} data-past={item.date.getTime() < now || undefined}>
        <td className="mono">{dateFormat.format(item.date)}</td>
        <td><strong>{item.kind}</strong>{item.calculated && <span className="calc"> · calculated: {item.calculated}</span>}</td>
        <td className="mono">{relative(item.date, now)}</td>
        <td><button type="button" className="text-button" onClick={() => onOpen(item.page, item.sentence)} title={item.sentence}>p.{item.page}</button></td>
      </tr>)}</tbody>
    </table>}
    {periods.length > 0 && <>
      <p className="field-label">Periods and deadlines</p>
      <ul className="period-list">{periods.slice(0, 16).map(item => <li key={item.key}>
        <span className="period-amount">{item.label}</span>
        <span className="period-kind">{item.kind}</span>
        <span className="period-text">{item.sentence.length > 160 ? `${item.sentence.slice(0, 160)}…` : item.sentence}</span>
        <button type="button" className="text-button" onClick={() => onOpen(item.page, item.sentence)}>p.{item.page}</button>
      </li>)}</ul>
    </>}
  </section>;
}
