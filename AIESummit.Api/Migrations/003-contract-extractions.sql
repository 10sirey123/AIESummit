CREATE OR REPLACE FUNCTION aiesummit_preserve_analysis_page() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (NEW."AnalysisId", NEW."OcrPageId", NEW."Number", NEW."Markdown", NEW."ContentHash")
        IS DISTINCT FROM (OLD."AnalysisId", OLD."OcrPageId", OLD."Number", OLD."Markdown", OLD."ContentHash") THEN
        RAISE EXCEPTION 'Analysis page text and source identity are immutable';
    END IF;
    RETURN NEW;
END $$;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'aiesummit_immutable_analysis_page') THEN
        CREATE TRIGGER aiesummit_immutable_analysis_page BEFORE UPDATE ON "PageTextRevisions"
            FOR EACH ROW EXECUTE FUNCTION aiesummit_preserve_analysis_page();
    END IF;
END $$;
