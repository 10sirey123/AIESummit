using Microsoft.EntityFrameworkCore;

namespace AIESummit.Domain;

/// <summary>Additive seed registry upgrade shared by bootstrap and the explicit operator command.</summary>
public static class SeedSchema
{
    public static async Task ApplyAsync(AIESummitDb db, CancellationToken cancellationToken = default)
    {
        await using var transaction = await db.Database.BeginTransactionAsync(cancellationToken);
        await db.Database.ExecuteSqlRawAsync("SELECT pg_advisory_xact_lock(825833001)", cancellationToken);
        await ApplyInTransactionAsync(db, cancellationToken);
        await transaction.CommitAsync(cancellationToken);
    }

    public static Task ApplyInTransactionAsync(AIESummitDb db, CancellationToken cancellationToken = default)
        => db.Database.ExecuteSqlRawAsync(Sql, cancellationToken);

    public const string Sql = """
        CREATE TABLE IF NOT EXISTS "SeedIdentities" (
            "ID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "DateCreated" timestamp with time zone NOT NULL,
            "LastModified" timestamp with time zone NULL,
            "Venture" character varying(80) NOT NULL,
            "SeedSet" character varying(160) NOT NULL,
            "EntityType" character varying(512) NOT NULL,
            "Tag" character varying(256) NOT NULL,
            "RecordId" integer NOT NULL,
            "OwnsRecord" boolean NOT NULL
        );
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_SeedIdentities_Venture_EntityType_Tag"
            ON "SeedIdentities" ("Venture", "EntityType", "Tag");
        CREATE INDEX IF NOT EXISTS "IX_SeedIdentities_Venture_SeedSet_EntityType_RecordId"
            ON "SeedIdentities" ("Venture", "SeedSet", "EntityType", "RecordId");
        """;
}
